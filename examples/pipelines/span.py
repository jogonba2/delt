def evaluate(predictions, data, label_names) -> None:
    """Exact-match precision, recall and F1 per label, comparing (span text, label) pairs."""
    tp, fp, fn = Counter(), Counter(), Counter()
    for spans, (_, gold) in zip(predictions, data, strict=True):
        pred = Counter((s.text, label_names[s.label]) for s in spans)
        ref = Counter(gold)
        for key in pred | ref:
            hit = min(pred[key], ref[key])
            tp[key[1]] += hit
            fp[key[1]] += pred[key] - hit
            fn[key[1]] += ref[key] - hit

    def prf(t, p, n):
        precision = t / (t + p) if t + p else 0.0
        recall = t / (t + n) if t + n else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        return precision, recall, f1

    print(f"{'label':<14}{'precision':>10}{'recall':>10}{'f1':>10}{'support':>10}")
    for label in sorted(set(tp) | set(fp) | set(fn)):
        p, r, f = prf(tp[label], fp[label], fn[label])
        print(f"{label:<14}{p:>10.2f}{r:>10.2f}{f:>10.2f}{tp[label] + fn[label]:>10}")
    p, r, f = prf(sum(tp.values()), sum(fp.values()), sum(fn.values()))
    print(f"{'micro avg':<14}{p:>10.2f}{r:>10.2f}{f:>10.2f}{sum(tp.values()) + sum(fn.values()):>10}")


